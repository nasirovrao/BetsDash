-- Метка "источник пика" на ставке (CHANGELOG.md, приоритет №1, решено
-- 30.08.2026, реализовано 31.08.2026) — позволяет пометить, чья это была
-- ставка: своя (поле пустое/NULL) или конкретного каппера (свободный текст,
-- обычно его юзернейм/имя), и смотреть отдельную статистику по каждому
-- источнику на новой странице cappers.html, не заводя под каждого каппера
-- отдельный канал.
--
-- Намеренно text и NULLable, без CHECK на допустимые значения (тот же
-- подход, что уже применялся к discipline до Milestone 20, и остаётся у
-- bookmaker/tournament/match/pick сегодня) — это свободный текст, который
-- пользователь вводит через <datalist> с автодополнением по уже введённым
-- значениям, а не фиксированный enum. NULL/пустая строка трактуются кодом
-- как "своя ставка" (см. keyFn в app.html/cappers.html) — намеренно НЕ
-- храним литеральную строку 'Своя ставка' в базе, чтобы не плодить два
-- разных представления одного и того же ("пусто" и "'Своя ставка'"),
-- которые легко рассинхронизировать при будущих правках.
--
-- Безопасно перезапускать: add column if not exists.

alter table public.bets add column if not exists pick_source text;
