-- CyberValue / EDGE — миграция Milestone 31: скрытие букмекера
-- от публики (02.09.2026).
--
-- ЧТО ДОБАВЛЕНО:
-- settings.hidden_bookmakers — список (массив текста) названий букмекеров,
-- которые владелец канала не хочет показывать посторонним (например
-- "ставлю на Пинко, но не хочу, чтобы это видели в ленте"). Управляется
-- на bookmakers.html (чекбокс "Скрывать от публики" у каждой карточки).
--
-- Скрытие касается ТОЛЬКО публичных страниц (public.html, feed.html) —
-- сам владелец на своих приватных страницах (app.html, bookmakers.html и
-- т.д.) всегда видит реальные названия, это чисто про то, что видят
-- посторонние. Скрытые букмекеры не пропадают из ленты и со статистики —
-- просто показываются под общей меткой "Скрыто" (в т.ч. в разбивке "По
-- букмекерам" на публичном профиле — ставки на скрытых букмекеров там
-- объединяются в одну группу "Скрыто", а не пропадают из счёта вовсе,
-- иначе цифры ROI/винрейт/профит на публичном профиле разъехались бы с
-- приватными).
--
-- default пустой массив — у канала без единого скрытого букмекера
-- публичные страницы выглядят ровно так же, как сейчас.
--
-- Вставь целиком в Supabase → SQL Editor → New query → Run.
-- Безопасно выполнять повторно.
-- ============================================================

alter table public.settings add column if not exists hidden_bookmakers text[] not null default '{}';
