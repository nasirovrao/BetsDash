-- ============================================================
-- CyberValue / EDGE — миграция Milestone 36: одна ставка, разбитая между
-- НЕСКОЛЬКИМИ букмекерами (одна и та же реальная ставка физически лежит
-- несколькими строками bets — по одной на каждого букмекера) — по прямому
-- запросу 09.09.2026: "ставлю Elite Series VIP на Cloudbet на $10 из-за
-- лимитов, добираю ту же ставку на Олимпе на 2000₽ — хочу чтобы это была
-- одна ставка, а карточка делилась на две части".
--
-- Решение: НЕ отдельная таблица-родитель, а просто общий group_id у строк
-- bets, которые являются "ногами" одной ставки — тот же дух, что уже есть
-- у экспрессов (несколько СОБЫТИЙ внутри одной строки через текст в поле
-- pick), только наоборот: здесь несколько СТРОК (разные букмекеры/кэфы/
-- суммы) представляют одну ставку. Все общие поля (матч, пик, дисциплина,
-- результат, дата, источник пика и т.д.) остаются одинаковыми в каждой
-- строке-ноге — это дублирование данных, но взамен НИЧЕГО не пришлось
-- переписывать в RLS/select-запросах/CLV/Telegram-импорте, они продолжают
-- работать как с обычными строками bets, просто теперь их может быть
-- несколько с одним group_id.
--
-- "Сколько это СТАВОК" (счётчики "N ставок" на дашборде и во всех
-- разбивках) — уже посчитано на уровне lib.js (computeStats/groupBetLegs,
-- см. коммит в lib.js) так, чтобы группа считалась ОДНОЙ ставкой, а не по
-- числу строк-ног. Здесь, в схеме, никакой отдельной логики для этого не
-- нужно.
--
-- Требует применённого schema.sql (таблица bets).
-- Вставь целиком в Supabase → SQL Editor → New query → Run.
-- Безопасно выполнять повторно.
-- ============================================================

alter table public.bets add column if not exists group_id uuid;

-- Ускоряет "все ноги этой ставки" (delete/update .eq('group_id', ...) при
-- редактировании/удалении разбитой ставки, см. app.html) — частичный индекс,
-- потому что у подавляющего большинства строк group_id всегда null (обычная
-- ставка на одного букмекера), индексировать их бессмысленно.
create index if not exists bets_group_id_idx on public.bets (group_id) where group_id is not null;
