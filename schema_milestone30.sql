-- ============================================================
-- CyberValue / EDGE — миграция Milestone 30: личная валюта
-- отображения дашбордов (02.09.2026).
--
-- ЧТО ДОБАВЛЕНО:
-- profiles.display_currency — ЛИЧНАЯ настройка каждого пользователя, ЧТО
-- показывать (доллары/рубли/евро/тенге/гривны) на его дашбордах, в дневнике,
-- банке, публичном профиле, ленте. НЕ меняет то, как данные ХРАНЯТСЯ —
-- bets.stake, withdrawals.amount и всё остальное как было в долларах, так
-- и остаётся, для абсолютно всех пользователей, старых и новых. Меняется
-- только КАК число показывается КОНКРЕТНОМУ зрителю — конвертация на лету
-- по текущему курсу (open.er-api.com, без ключа) в момент отображения
-- страницы, см. getDisplayCurrency() в lib.js.
--
-- Почему не хранить ставки сразу в родной валюте пользователя: (1) ROI/
-- профит/винрейт по всему приложению считаются как есть, сложное
-- переписывание математики под мультивалютность не нужно, раз задача —
-- просто "хочу видеть рубли вместо долларов"; (2) в ленте (feed.html)
-- сравниваются капперы МЕЖДУ СОБОЙ — если бы каждый хранил в своей
-- валюте, сравнение "Профит" было бы нечестным (500₽ и $500 — не одно и
-- то же); раз хранение всегда в долларах, конвертация происходит только
-- один раз, в валюту ТОГО, КТО СМОТРИТ, и сравнения остаются корректными.
--
-- default 'USD' — у пользователя без единой настройки страницы выглядят
-- ровно так же, как сейчас, ничего не меняется.
--
-- Вставь целиком в Supabase → SQL Editor → New query → Run.
-- Безопасно выполнять повторно.
-- ============================================================

alter table public.profiles add column if not exists display_currency text not null default 'USD';

alter table public.profiles drop constraint if exists profiles_display_currency_check;
alter table public.profiles add constraint profiles_display_currency_check
  check (display_currency in ('USD', 'RUB', 'EUR', 'KZT', 'UAH'));
