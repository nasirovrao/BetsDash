-- метрика "Доходность по флетам" (28.08.2026).
--
-- ЧТО ДОБАВЛЕНО:
-- settings.default_flat_size — необязательная сумма в $, которая стоит за
-- "1 флет" в конкретном канале (личном дневнике/Cybervalue/др.). Если
-- задана — на странице "Ставки" (app.html) сумма ставки подставляется сама
-- при изменении множителя "Флет (×)" (например флет=100$, поставил 1.5× —
-- сумма подставится 150$ автоматически), без необходимости вписывать её
-- отдельно. Поле необязательное (NULL по умолчанию) — если не задано,
-- форма ведёт себя как раньше, сумму нужно вписывать вручную.
--
-- "Доходность по флетам" (новая карточка на дашборде) сама по себе НЕ
-- зависит от этой колонки — она считается от bet.flat_mult (множитель,
-- который уже был у каждой ставки и раньше), см. computeFlatStats() в
-- lib.js. default_flat_size нужен только для удобства ВВОДА ставок, не
-- для самого расчёта метрики.
--
-- Вставь целиком в Supabase → SQL Editor → New query → Run.
-- Безопасно выполнять повторно.
-- ============================================================

alter table public.settings add column if not exists default_flat_size numeric check (default_flat_size is null or default_flat_size > 0);
