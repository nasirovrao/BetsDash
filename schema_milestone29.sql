-- ============================================================
-- CyberValue / EDGE — миграция Milestone 29: заметки о визуальном
-- стиле букмекеров, чтобы модель "запоминала" незнакомые интерфейсы
-- (02.09.2026).
--
-- ЧТО ДОБАВЛЕНО:
-- settings.bookmaker_notes — объект {имя_букмекера: текст_заметки}.
-- Пользователь может (необязательно) описать, как выглядит интерфейс
-- букмекера, добавляя его через "+" на app.html (см. Milestone 28,
-- custom_bookmakers) — например "тёмная тема, оранжевый акцент, круглые
-- зелёные/красные иконки статуса слева, время сверху карточки". Эти
-- заметки подмешиваются в промпт распознавания скриншотов/Telegram-постов
-- (parse-bet-screenshot и telegram-webhook) как дополнительный контекст —
-- по сути ручное "обучение" модели незнакомым интерфейсам без файнтюна,
-- через явное текстовое описание, а не запоминание самих картинок.
--
-- Повод: репорт "плохо распознаёт скрины с конторы Пинко, пишет скриншот
-- не распознан" — Пинко не было в захардкоженном списке "узнаваемых"
-- букмекеров внутри промпта модели.
--
-- default пустой объект — у канала без единой заметки строка просто не
-- добавляет ничего в промпт (как и было раньше).
--
-- Вставь целиком в Supabase → SQL Editor → New query → Run.
-- Безопасно выполнять повторно.
-- ============================================================

alter table public.settings add column if not exists bookmaker_notes jsonb not null default '{}'::jsonb;
