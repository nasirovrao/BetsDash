-- ============================================================
-- CyberValue App — Milestone 4: усиливаем RLS на UPDATE
-- ============================================================
-- Политики "update own bets" / "update own settings" проверяли только то,
-- какую СТРОКУ разрешено редактировать (USING), но не то, какие значения
-- разрешено в неё записать (WITH CHECK). Из-за этого пользователь теоретически
-- мог обновить свою же ставку/настройки и переписать в них user_id на чужой —
-- не приводит к утечке чужих данных на чтение, но ломает целостность (строка
-- "пропадает" у одного и появляется у чужого аккаунта без его ведома).
-- Добавляем WITH CHECK, чтобы после любого UPDATE строка гарантированно
-- оставалась за тем же пользователем.
--
-- Вставь целиком в Supabase → SQL Editor → New query → Run
-- (безопасно выполнять повторно)
-- ============================================================

alter policy "update own bets" on public.bets
  with check (auth.uid() = user_id);

alter policy "update own settings" on public.settings
  with check (auth.uid() = user_id);
